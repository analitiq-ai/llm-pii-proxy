_WORD = r"[A-Z][a-z]+"
_PLACE = rf"{_WORD}(?: {_WORD}){{0,2}}"
_US_LOCALITY = rf"{_PLACE}, (?:{'|'.join(_US_STATES)}) \d{{5}}(?:-\d{{4}})?"
_UK_POSTCODE = r"[A-Z]{1,2}\d[A-Z\d]? \d[A-Z]{2}"
_STREET = (
    rf"\d{{1,6}}[A-Z]? {_WORD}(?: {_WORD}){{0,3}} {_SUFFIX}"
    r"(?: (?:N|S|E|W|NE|NW|SE|SW))?"
    r"(?:,? (?:Apt|Suite|Unit|Flat)\.? ?[A-Z\d]+)?"
)
_LOCALITY = rf"(?:{_US_LOCALITY}|{_PLACE},? {_UK_POSTCODE}|{_PLACE})"

PATTERNS = [
    Pattern("street address", rf"\b{_STREET}(?:, {_LOCALITY})?\b", 0.6),
    Pattern("US city, state and ZIP", rf"\b{_US_LOCALITY}\b", 0.5),
    Pattern("UK postcode", rf"\b{_UK_POSTCODE}\b", 0.5),
]


def recognizer() -> PatternRecognizer:
    # Presidio's default flags include IGNORECASE, which would let any lowercase phrase ending in
    # "way" or "st" match. Capitalisation is what separates a street name from prose and code.
    return PatternRecognizer(
        supported_entity=ENTITY, patterns=PATTERNS, global_regex_flags=re.MULTILINE
    )
